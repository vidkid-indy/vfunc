export function generateComponents(lang) {
  const t = TEXT[lang];
  const catalog = JSON.parse(read('layer2/catalog.json'));
  const decls = [];
  for (const path of TYPES) decls.push(...readDeclarations(read(path)));
  const byName = new Map(decls.map((d) => [d.name, d]));
  const used = new Set();

  const out = [];
  for (const category of catalog.categories) {
    out.push('', '## ' + t.categories[category]);
    for (const c of catalog.components.filter((x) => x.category === category)) {
      out.push('', '### ' + c.names.map((n) => '`' + n + '`').join(' · ') + ' — ' + c.tier, '', c.summary[lang]);
      const notes = [];
      if (c.file === 'data') notes.push(t.dataFile);
      if (c.messages.length) notes.push(t.messages + ': ' + c.messages.map((k) => '`' + k + '`').join(', '));
      if (notes.length) out.push('', notes.join(' '));
      out.push('', '```js', c.example, '```');
      const ts = [];
      for (const name of c.names) {
        const fn = byName.get(name);
        if (!fn || fn.kind !== 'function') throw new Error('components: no declaration for ' + name);
        const props = fn.props && byName.get(fn.props);
        // A props interface is shown with its first component (vsSwitch reuses vsCheckbox's).
        if (props && props.kind === 'interface' && !used.has(props.name)) {
          ts.push(render(props));
          used.add(props.name);
        }
        if (fn.doc) ts.push('// ' + fn.doc);
        ts.push(render(fn));
        used.add(fn.name);
      }
      out.push('', '```ts', ts.join('\n'), '```');
    }
  }

  out.push('', t.adapters);
  for (const file of readdirSync(join(ROOT, ADAPTER_TYPES)).sort()) {
    const ds = readDeclarations(read(ADAPTER_TYPES + '/' + file));
    const fn = ds.find((d) => d.kind === 'function');
    out.push('', '### `' + fn.name + '`', '', t.adapterFile + ': `vfunc-' + file.replace(/\.d\.ts$/, '') + '.js`', '', '```ts', ds.map(render).join('\n'), '```');
  }

  // Shared types (the ones no component shows) come first: the components refer to them.
  const shared = decls.filter((d) => !used.has(d.name) && d.kind !== 'function').map(render).join('\n');
  return [t.title, '', t.generated, '', ...t.intro, '', t.shared, '', '```ts', shared, '```'].concat(out).join('\n') + '\n';
}

/** Writes (or, with check, compares) both files. Returns the stale paths. */
export function writeComponents(options) {
  const check = !!(options && options.check);
  const stale = [];
  for (const lang of Object.keys(COMPONENTS_MD)) {
    const text = generateComponents(lang);
    const full = join(ROOT, COMPONENTS_MD[lang]);
    if (!existsSync(full) || readFileSync(full, 'utf8') !== text) {
      stale.push(COMPONENTS_MD[lang]);
      if (!check) writeFileSync(full, text);
    }
  }
  return stale;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const check = process.argv.indexOf('--check') >= 0;
  const stale = writeComponents({ check: check });
  if (check && stale.length) {
    console.error('Out of date (run npm run build): ' + stale.join(', '));
    process.exit(1);
  }
  console.log('components.md: ' + (stale.length ? (check ? 'stale' : 'written') : 'up to date'));
}

const read = (path) => readFileSync(join(ROOT, path), 'utf8').replace(/\r\n/g, '\n');

// ---- d.ts reading -------------------------------------------------------------------------------

/** Index of the character that closes the bracket at `start`, or of the `;` ending a statement. */
function scanTo(text, start, until) {
  let depth = 0;
  for (let i = start; i < text.length; i++) {
    const c = text[i];
    if (c === '/' && text[i + 1] === '*') { i = text.indexOf('*/', i + 2) + 1; continue; }
    if (c === '/' && text[i + 1] === '/') { i = text.indexOf('\n', i); continue; }
    if (c === '\'') { i = text.indexOf('\'', i + 1); continue; }
    if (c === '{' || c === '(' || c === '[' || (c === '<')) depth++;
    else if (c === '}' || c === ')' || c === ']' || (c === '>' && text[i - 1] !== '=')) {
      depth--;
      if (until === 'close' && depth === 0) return i;
    } else if (until === ';' && c === ';' && depth === 0) return i;
  }
  throw new Error('components: unbalanced declaration at ' + text.slice(start, start + 60));
}

const oneLine = (s) => s.replace(/\/\*[\s\S]*?\*\//g, ' ').replace(/\/\/[^\n]*/g, ' ').replace(/\s+/g, ' ').trim();

/** First sentence of the JSDoc right before `at`, if any. */
function docBefore(text, at) {
  const before = text.slice(0, at).replace(/\s+$/, '');
  if (!before.endsWith('*/')) return '';
  const open = before.lastIndexOf('/**');
  if (open < 0) return '';
  return before.slice(open + 3, before.length - 2).replace(/^\s*\* ?/gm, ' ').replace(/\s+/g, ' ').trim();
}

/** Splits an interface body into members at the top-level `;`. */
function members(body) {
  const out = [];
  let from = 0;
  for (;;) {
    let end;
    try { end = scanTo(body, from, ';'); } catch (err) { break; }
    const m = oneLine(body.slice(from, end));
    if (m) out.push(m);
    from = end + 1;
  }
  const rest = oneLine(body.slice(from));
  if (rest) out.push(rest);
  return out;
}

/** The exported interfaces, types and functions of a d.ts file, in order. */
export function readDeclarations(text) {
  const out = [];
  const re = /^export (interface|type|declare function) (\w+)/gm;
  let m;
  while ((m = re.exec(text))) {
    const kind = m[1] === 'declare function' ? 'function' : m[1];
    const start = m.index;
    const doc = docBefore(text, start);
    if (kind === 'interface') {
      const open = text.indexOf('{', start);
      const close = scanTo(text, open, 'close');
      out.push({ kind, name: m[2], doc, head: oneLine(text.slice(start + 7, open)), members: members(text.slice(open + 1, close)) });
      re.lastIndex = close;
    } else {
      const end = scanTo(text, start, ';');
      const decl = oneLine(text.slice(start + 7, end)).replace(/^declare function /, 'function ');
      const d = { kind, name: m[2], doc, decl };
      if (kind === 'function') {
        // The props type: the first parameter's type name, generics dropped.
        const param = /\(\s*\w+\??:\s*(\w+)/.exec(decl);
        d.props = param ? param[1] : null;
      }
      out.push(d);
      re.lastIndex = end;
    }
  }
  return out;
}

function render(d) {
  if (d.kind === 'interface') return d.head + ' {\n' + d.members.map((x) => '  ' + x + ';').join('\n') + '\n}';
  return d.decl + ';';
}


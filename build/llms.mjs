// layer1/ai/llms-full.txt: the complete reference for LLMs, generated so it never drifts from
// its sources (D-019): llms.txt (English summary) + ai-docs/vfunc_manual.md (the reference, in
// Korean) + the type declarations (English). Called by build.mjs; runnable on its own.
//
//   node build/llms.mjs           write layer1/ai/llms-full.txt
//   node build/llms.mjs --check   fail when it is out of date

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(fileURLToPath(new URL('.', import.meta.url)), '..');
export const LLMS_FULL = 'layer1/ai/llms-full.txt';

const SOURCES = {
  summary: 'layer1/ai/llms.txt',
  manual: 'ai-docs/vfunc_manual.md',
  types: ['layer1/types/vfunc.d.ts', 'layer1/types/global.d.ts', 'layer1/types/plugins/update.d.ts']
};

function read(path) {
  return readFileSync(join(ROOT, path), 'utf8').replace(/\r\n/g, '\n').trim();
}

export function generateLlmsFull() {
  const version = JSON.parse(read('package.json')).version;
  const parts = [
    '# vfunc.js — full reference for LLMs (v' + version + ')',
    '',
    '> Generated by build/llms.mjs from llms.txt, ai-docs/vfunc_manual.md and layer1/types/*.d.ts. Do not edit.',
    '> The summary and the types are in English; the reference manual is in Korean (the project\'s single source).',
    '> build/llms.mjs가 생성합니다. 요약과 타입은 영어, 레퍼런스 매뉴얼은 한국어(단일 원본)입니다. 직접 고치지 마세요.',
    '',
    '---',
    '',
    '# Part 1 — Summary and rules (llms.txt)',
    '',
    read(SOURCES.summary).replace(/^# vfunc\.js\n/, ''),
    '',
    '---',
    '',
    '# Part 2 — Reference manual (ai-docs/vfunc_manual.md, Korean)',
    '',
    read(SOURCES.manual).replace(/^# [^\n]*\n/, ''),
    '',
    '---',
    '',
    '# Part 3 — Type declarations (the public API boundary)'
  ];
  for (const path of SOURCES.types) {
    parts.push('', '## ' + path.replace('layer1/', ''), '', '```ts', read(path), '```');
  }
  return parts.join('\n') + '\n';
}

/** Writes (or, with check, compares) llms-full.txt. Returns true when it was stale. */
export function writeLlms(options) {
  const check = !!(options && options.check);
  const text = generateLlmsFull();
  const full = join(ROOT, LLMS_FULL);
  const stale = !existsSync(full) || readFileSync(full, 'utf8') !== text;
  if (stale && !check) writeFileSync(full, text);
  return stale;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const check = process.argv.indexOf('--check') >= 0;
  const stale = writeLlms({ check: check });
  if (check && stale) {
    console.error('Out of date (run npm run build): ' + LLMS_FULL);
    process.exit(1);
  }
  console.log(LLMS_FULL + ': ' + (stale ? (check ? 'stale' : 'written') : 'up to date'));
}

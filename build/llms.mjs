// layer1/ai/llms-full.txt: the complete reference for LLMs, generated so it never drifts from
// its sources: llms.txt (the summary and rules) + the English website pages (the user guide and
// the API reference) + the type declarations. Called by build.mjs; runnable on its own.
//
//   node build/llms.mjs           write layer1/ai/llms-full.txt
//   node build/llms.mjs --check   fail when it is out of date

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(fileURLToPath(new URL('.', import.meta.url)), '..');
export const LLMS_FULL = 'layer1/ai/llms-full.txt';

const SOURCES = {
  summary: 'layer1/ai/llms.txt',
  // Website pages in reading order (site/content/en, the translation of the Korean original).
  pages: ['getting-started', 'guide', 'spa', 'design', 'extend', 'deploy', 'api', 'faq'],
  types: ['layer1/types/vfunc.d.ts', 'layer1/types/global.d.ts', 'layer1/types/plugins/update.d.ts', 'layer1/types/plugins/shortcut.d.ts']
};

function read(path) {
  return readFileSync(join(ROOT, path), 'utf8').replace(/\r\n/g, '\n').trim();
}

function sri(file) {
  return 'sha384-' + createHash('sha384').update(readFileSync(join(ROOT, 'layer1/dist', file))).digest('base64');
}

/** A website page as plain Markdown: headings one level down, generated blocks as text. */
function page(slug, version) {
  const install = [
    '```html',
    '<script src="https://cdn.jsdelivr.net/npm/vfunc@' + version + '/dist/vfunc.min.js"',
    '        integrity="' + sri('vfunc.min.js') + '" crossorigin="anonymous"></script>',
    '```'
  ].join('\n');
  return read('site/content/en/' + slug + '.md')
    .replace(/@VERSION@/g, version)
    .replace(/^\{\{install\}\}$/gm, install)
    .replace(/^\{\{(\w+)\}\}$/gm, '(See the website for the $1 list.)')
    .replace(/^(#+) /gm, '#$1 ');
}

export function generateLlmsFull() {
  const version = JSON.parse(read('package.json')).version;
  const parts = [
    '# vfunc.js — full reference for LLMs (v' + version + ')',
    '',
    '> Generated by build/llms.mjs from llms.txt, the website pages (site/content/en) and layer1/types/*.d.ts. Do not edit.',
    '> build/llms.mjs가 생성합니다. 직접 고치지 마세요. 한국어 문서는 사이트(site/content/ko)에 있습니다.',
    '',
    '---',
    '',
    '# Part 1 — Summary and rules (llms.txt)',
    '',
    read(SOURCES.summary).replace(/^# vfunc\.js\n/, ''),
    '',
    '---',
    '',
    '# Part 2 — Guide and API reference (website)'
  ];
  for (const slug of SOURCES.pages) parts.push('', page(slug, version));
  parts.push('', '---', '', '# Part 3 — Type declarations (the public API boundary)');
  for (const path of SOURCES.types) {
    parts.push('', '## ' + path.replace('layer1/', ''), '', '```ts', read(path), '```');
  }
  return parts.join('\n') + '\n';
}

/** Writes (or, with check, compares) llms-full.txt. Returns true when it was stale. */
export function writeLlms(options) {
  const check = !!(options && options.check);
  const text = generateLlmsFull();
  const full = join(ROOT, LLMS_FULL);
  const stale = !existsSync(full) || readFileSync(full, 'utf8') !== text;
  if (stale && !check) writeFileSync(full, text);
  return stale;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const check = process.argv.indexOf('--check') >= 0;
  const stale = writeLlms({ check: check });
  if (check && stale) {
    console.error('Out of date (run npm run build): ' + LLMS_FULL);
    process.exit(1);
  }
  console.log(LLMS_FULL + ': ' + (stale ? (check ? 'stale' : 'written') : 'up to date'));
}
